// THE DIVINE ATLAS — data loader + derived indexes (build-time, no DB).
// Loads /data/<culture>/*.json into typed structures.
import fs from 'fs';
import path from 'path';
import {
  Entity, Relationship, Myth, Cosmology, Artwork, TimelineEvent,
  Uncertainty, SourceRef, Culture, CultureData, GraphData,
} from './types';

export const CULTURES = ['japanese', 'greek', 'norse', 'egyptian', 'slavic', 'mesopotamian'] as const;
export const ALL_CULTURES = CULTURES;

const ROOT = path.join(process.cwd(), 'data');

function loadJSON<T>(rel: string): T {
  const p = path.join(ROOT, rel);
  return JSON.parse(fs.readFileSync(p, 'utf8'));
}

const cache: Record<string, CultureData> = {};

export function loadCulture(culture: string): CultureData {
  if (cache[culture]) return cache[culture];
  const meta = (loadJSON<Culture[]>('cultures.json')).find((c) => c.id === culture);
  const entities: Entity[] = loadJSON(`${culture}/entities.json`);
  const relationships: Relationship[] = loadJSON(`${culture}/relationships.json`);
  const myths: Myth[] = loadJSON(`${culture}/myths.json`);
  const cosmology: Cosmology = loadJSON(`${culture}/cosmology.json`);
  const artworks: Artwork[] = loadJSON(`${culture}/artworks.json`);
  const timeline: TimelineEvent[] = loadJSON(`${culture}/timeline.json`);
  const uncertainties: Uncertainty[] = loadJSON(`${culture}/uncertainties.json`);
  // Machine-readable bibliography: data/<culture>/sources.json (generated by
  // scripts/integrate.mjs from the authoritative research/<culture>/sources.md).
  // Fallback: rebuild from entity primary_sources if sources.json is missing.
  let sources: SourceRef[] = [];
  try {
    sources = loadJSON<SourceRef[]>(`${culture}/sources.json`);
  } catch {
    const srcMap = new Map<string, SourceRef>();
    for (const e of entities) for (const s of e.primary_sources || []) if (s?.ref) srcMap.set(s.ref, s);
    sources = [...srcMap.values()].sort((a, b) => num(a.ref) - num(b.ref));
  }
  const d: CultureData = {
    culture, meta, entities, relationships, myths, cosmology, artworks, timeline, uncertainties, sources,
  };
  cache[culture] = d;
  return d;
}

function num(ref: string) { const n = parseInt(String(ref).replace(/\D/g, ''), 10); return isNaN(n) ? 999 : n; }

// ---- global indexes (lazy, memoized) ----
let _all: { byId: Map<string, Entity>; cultureOf: Record<string, CultureData> } | null = null;
export function allCultures(): Record<string, CultureData> {
  const out: Record<string, CultureData> = {};
  for (const c of CULTURES) out[c] = loadCulture(c);
  return out;
}
export function entityById(id: string): Entity | undefined {
  if (!_all) {
    _all = { byId: new Map(), cultureOf: allCultures() };
    for (const d of Object.values(_all.cultureOf)) for (const e of d.entities) _all.byId.set(e.id, e);
  }
  return _all.byId.get(id);
}
export function cultureOfId(id: string): string | undefined {
  return id?.split('-')[0] ? entityById(id)?.culture : undefined;
}

// ---- global (cross-culture) dataset for the /graph explorer ----
let _global: GraphData | null = null;
export function globalData(): GraphData {
  if (_global) return _global;
  const all = Object.values(allCultures());
  _global = {
    entities: all.flatMap((d) => d.entities),
    relationships: all.flatMap((d) => d.relationships),
    myths: all.flatMap((d) => d.myths),
    artworks: all.flatMap((d) => d.artworks),
  };
  return _global;
}

// ---- graph queries ----
type Adj = { out: Relationship[]; inn: Relationship[] };
export function neighbors(id: string, types?: string[], depth = 1): { ids: string[]; rels: Relationship[] } {
  const d = loadCulture(entityById(id)?.culture || 'japanese');
  const adj: Record<string, Adj> = {};
  for (const e of d.entities) adj[e.id] = { out: [], inn: [] };
  for (const r of d.relationships) {
    if (types && !types.includes(r.type)) continue;
    (adj[r.from]?.out ?? []).push(r);
    (adj[r.to]?.inn ?? []).push(r);
  }
  const ids = new Set<string>();
  const rels: Relationship[] = [];
  let frontier = [id];
  for (let lvl = 0; lvl < depth; lvl++) {
    const next: string[] = [];
    for (const n of frontier) {
      for (const r of [...(adj[n]?.out || []), ...(adj[n]?.inn || [])]) {
        if (!rels.includes(r)) rels.push(r);
        const other = r.from === n ? r.to : r.from;
        if (other !== id && !ids.has(other)) { ids.add(other); if (lvl + 1 < depth) next.push(other); }
      }
    }
    frontier = next;
  }
  return { ids: [...ids], rels };
}

export function ancestors(id: string, maxDepth = 6): string[] {
  return walk(id, ['PARENT_OF'], true, maxDepth);
}
export function descendants(id: string, maxDepth = 6): string[] {
  return walk(id, ['PARENT_OF'], false, maxDepth);
}
export function enemiesOf(id: string): string[] {
  const { rels } = neighbors(id, ['ENEMY_OF', 'FOUGHT', 'KILLED'], 1);
  return [...new Set(rels.map(r => (r.from === id ? r.to : r.from)))];
}
function walk(id: string, types: string[], up: boolean, maxDepth: number): string[] {
  const d = loadCulture(entityById(id)?.culture || 'japanese');
  const seen = new Set<string>([id]);
  const out: string[] = [];
  let frontier = [id];
  for (let i = 0; i < maxDepth; i++) {
    const next: string[] = [];
    for (const n of frontier) {
      for (const r of d.relationships) {
        if (!types.includes(r.type)) continue;
        const from = up ? r.to : r.from; // parent link: PARENT_OF is parent->child
        const to = up ? r.from : r.to;
        if (from === n && !seen.has(to)) { seen.add(to); out.push(to); next.push(to); }
      }
    }
    frontier = next;
    if (!frontier.length) break;
  }
  return out;
}

// ---- search index (names, alt names, domains, symbols, animals, weapons, places) ----
let _search: Record<string, { entities: string[]; myths: string[] }> | null = null;
export function searchIndex(): Record<string, { entities: string[]; myths: string[] }> {
  if (_search) return _search;
  const idx: Record<string, { entities: string[]; myths: string[] }> = {};
  const add = (term: string, kind: 'entities' | 'myths', id: string) => {
    const t = term.toLowerCase().trim();
    if (!t) return;
    for (const tok of t.split(/\s+/)) {
      if (tok.length < 3) continue;
      (idx[tok] ||= { entities: [], myths: [] });
      if (!idx[tok][kind].includes(id)) idx[tok][kind].push(id);
    }
  };
  for (const d of Object.values(allCultures())) {
    for (const e of d.entities) {
      for (const t of [e.name, e.native_name, ...(e.alternative_names || []),
        ...e.domains, ...(e.symbols || []), ...(e.animals || []), ...(e.weapons || []),
        ...(e.sacred_objects || []), ...(e.associated_places || [])]) add(t as string, 'entities', e.id);
    }
    for (const m of d.myths) { add(m.title, 'myths', m.id); add(m.summary, 'myths', m.id); }
  }
  _search = idx;
  return idx;
}
export function search(query: string): { entities: Entity[]; myths: Myth[] } {
  const q = query.toLowerCase().trim();
  if (!q) return { entities: [], myths: [] };
  const tokens = q.split(/\s+/);
  const scored = new Map<string, number>();
  const mythScore = new Map<string, number>();
  const idx = searchIndex();
  for (const tok of tokens) {
    const entry = idx[tok];
    if (!entry) continue;
    for (const id of entry.entities) scored.set(id, (scored.get(id) || 0) + 1);
    for (const id of entry.myths) mythScore.set(id, (mythScore.get(id) || 0) + 1);
  }
  const entities = [...scored.entries()].sort((a, b) => b[1] - a[1]).slice(0, 24)
    .map(([id]) => entityById(id)!).filter(Boolean);
  const allMyths = Object.values(allCultures()).flatMap((d) => d.myths);
  const mythById = new Map(allMyths.map((m) => [m.id, m]));
  const myths = [...mythScore.entries()].sort((a, b) => b[1] - a[1]).slice(0, 12)
    .map(([id]) => mythById.get(id)).filter(Boolean) as Myth[];
  return { entities, myths };
}
